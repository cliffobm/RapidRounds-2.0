function nr(
  scenarioId: string,
  stem: string,
  difficulty: 'easy' | 'medium' | 'hard' | 'critical',
  seconds: number,
  type: ItemType,
  correct: 0 | 1 | 2 | 3,
  opts: [string, string, string, string],
  dist: [string, string, string, string],
  why: string,
) {
  return buildMcqItem(scenarioId, S, {
    stem,
    difficulty,
    timerSeconds: seconds,
    type,
    status: 'needs_review',
    stemRationale: why,
    referenceText: REF_EDU,
    options: opts,
    correctIndex: correct,
    optionRationales: dist,
  });
}

